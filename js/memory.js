    markRead(no) {
      const d = this.read();
      if (d.read.indexOf(+no) < 0) d.read.push(+no);
      this.save(d);
      this.sync();
      return d.read.length;
    },
    takeRelic(no) {
      const d = this.read();
      if (d.relics.indexOf(+no) < 0) d.relics.push(+no);
      if (d.read.indexOf(+no) < 0) d.read.push(+no);
      this.save(d);
      this.sync();
      return d.relics.length;
    },
